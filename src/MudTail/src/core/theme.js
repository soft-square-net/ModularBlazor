// Theme & CSS/SCSS Exporter Utility in Vanilla JS

import { setNumerals } from './i18n.js';

const STORAGE_KEY = 'mud_vanilla_theme_config';

export const DEFAULT_THEME = {
  primary: '#594ae2',
  secondary: '#ff4081',
  borderRadius: 4,
  isDark: false,
  // Digits for numbers and dates: 'auto' (the browser's default for the language), 'latn' (1 2 3),
  // 'arab' (Arabic-Indic ١ ٢ ٣) or 'arabext' (۱ ۲ ۳). Saved with the theme; see i18n setNumerals().
  // null = no preference: whatever setLocale(…, { numerals }) / setNumerals() chose stays.
  numerals: null,
};

let currentTheme = { ...DEFAULT_THEME };

function hexToRgb(hex) {
  const cleanHex = hex.replace('#', '');
  const bigint = parseInt(cleanHex, 16);
  const r = (bigint >> 16) & 255;
  const g = (bigint >> 8) & 255;
  const b = bigint & 255;
  return `${r}, ${g}, ${b}`;
}

export function initTheme() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      currentTheme = { ...DEFAULT_THEME, ...JSON.parse(saved) };
    }
  } catch {
    // fallback
  }
  applyTheme(currentTheme);
  return currentTheme;
}

export function getTheme() {
  return { ...currentTheme };
}

export function updateTheme(updates) {
  currentTheme = { ...currentTheme, ...updates };
  applyTheme(currentTheme);
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(currentTheme));
  } catch {
    // ignore
  }

  // Dispatch custom event for reactive UI updates
  window.dispatchEvent(new CustomEvent('mud-theme-changed', { detail: currentTheme }));
  return currentTheme;
}

export function applyTheme(theme) {
  const root = document.documentElement;

  root.style.setProperty('--mud-palette-primary', theme.primary);
  root.style.setProperty('--mud-palette-primary-rgb', hexToRgb(theme.primary));

  root.style.setProperty('--mud-palette-secondary', theme.secondary);
  root.style.setProperty('--mud-palette-secondary-rgb', hexToRgb(theme.secondary));

  root.style.setProperty('--mud-default-borderradius', `${theme.borderRadius}px`);
  root.style.setProperty('--mud-input-borderradius', `${theme.borderRadius}px`);

  if (theme.isDark) {
    root.setAttribute('data-theme', 'dark');
  } else {
    root.removeAttribute('data-theme');
  }

  // Digits are part of the theme: an explicit choice is applied to i18n (raises mud-locale-changed when it changes).
  if (theme.numerals) setNumerals(theme.numerals);
}

/**
 * Generate exportable SCSS tokens string
 */
export function generateScssExport(theme = currentTheme) {
  return `// MudBlazor Material SCSS Design Tokens
// Generated by MudTail Theme Studio

$mud-palette-primary: ${theme.primary};
$mud-palette-primary-rgb: (${hexToRgb(theme.primary)});
$mud-palette-secondary: ${theme.secondary};
$mud-palette-secondary-rgb: (${hexToRgb(theme.secondary)});

$mud-default-borderradius: ${theme.borderRadius}px;
$mud-input-borderradius: ${theme.borderRadius}px;

// CSS Variables Injection
:root {
  --mud-palette-primary: #{$mud-palette-primary};
  --mud-palette-primary-rgb: #{$mud-palette-primary-rgb};
  --mud-palette-secondary: #{$mud-palette-secondary};
  --mud-palette-secondary-rgb: #{$mud-palette-secondary-rgb};

  --mud-default-borderradius: #{$mud-default-borderradius};
  --mud-input-borderradius: #{$mud-input-borderradius};
}

// Elevation & Rounded Utility Mixins
@mixin mud-rounded($radius: $mud-default-borderradius) {
  border-radius: $radius;
}
`;
}

